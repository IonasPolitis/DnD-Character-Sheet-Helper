const fs = require('fs');
const path = require('path');

const rulebookDir = path.join(__dirname, 'rulebook');
const outputFile = path.join(__dirname, 'registry.ts');

// Helper function to safely read folders and get filenames without '.json'
function scanFolder(folderName) {
    const dirPath = path.join(rulebookDir, folderName);
    if (!fs.existsSync(dirPath)) return [];
    return fs.readdirSync(dirPath)
        .filter(file => file.endsWith('.json'))
        .map(file => file.replace('.json', ''));
}

const classes = scanFolder('classes');
const classChoices = scanFolder(path.join('classes', 'classChoices'));
const feats = scanFolder('feats');
const races = scanFolder('races');
const items = scanFolder('items');
const rules = scanFolder('rules');
const spells = scanFolder('spells');

// --- MARKDOWN NOTE SCANNER ---
function scanMarkdownNotes() {
    const notes = [];

    // 1. Scan Root directory (ignoring README.md)
    fs.readdirSync(__dirname)
        .filter(file => file.endsWith('.md') && file.toLowerCase() !== 'readme.md')
        .forEach(file => {
            notes.push({
                // ADDED .toLowerCase() HERE
                name: file.replace('.md', '').toLowerCase(),
                filePath: path.join(__dirname, file)
            });
        });

    // 2. Scan rulebook/markdown directory
    const rulebookDir = path.join(__dirname, 'rulebook', 'markdown');
    if (fs.existsSync(rulebookDir)) {
        fs.readdirSync(rulebookDir)
            .filter(file => file.endsWith('.md'))
            .forEach(file => {
                notes.push({
                    // ADDED .toLowerCase() HERE
                    name: file.replace('.md', '').toLowerCase(),
                    filePath: path.join(rulebookDir, file)
                });
            });
    }

    return notes;
}

const markdownNotes = scanMarkdownNotes();

// Start building the file text
let out = `// ==========================================\n`;
out += `// THIS FILE IS AUTO-GENERATED BY A SCRIPT.\n`;
out += `// DO NOT EDIT THIS FILE MANUALLY.\n`;
out += `// ==========================================\n\n`;

// 1. Generate Imports for Upper Routers
out += `import classesMap from './rulebook/classes.json';\n`;
if (fs.existsSync(path.join(rulebookDir, 'backgrounds.json'))) {
    out += `import backgroundsMap from './rulebook/backgrounds.json';\n`;
} else {
    out += `const backgroundsMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'races.json'))) {
    out += `import racesMap from './rulebook/races.json';\n`;
} else {
    out += `const racesMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'items.json'))) {
    out += `import itemsMap from './rulebook/items.json';\n`;
} else {
    out += `const itemsMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'rules.json'))) {
    out += `import rulesMap from './rulebook/rules.json';\n`;
} else {
    out += `const rulesMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'general-feats.json'))) {
    out += `import generalFeatsMap from './rulebook/general-feats.json';\n`;
} else {
    out += `const generalFeatsMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'epic-boon-feats.json'))) {
    out += `import epicBoonFeatsMap from './rulebook/epic-boon-feats.json';\n`;
} else {
    out += `const epicBoonFeatsMap = {};\n`;
}

// 2. Generate Imports for Sub-folders
classes.forEach(c => {
    // Upgraded Regex: Strips ALL non-alphanumeric characters so JavaScript never breaks
    const safeName = c.replace(/[^a-zA-Z0-9]/g, '');
    out += `import class_${safeName} from './rulebook/classes/${c}.json';\n`;
});
classChoices.forEach(cc => {
    const safeName = cc.replace(/[^a-zA-Z0-9]/g, '');
    out += `import classChoice_${safeName} from './rulebook/classes/classChoices/${cc}.json';\n`;
});
feats.forEach(f => {
    const safeName = f.replace(/[^a-zA-Z0-9]/g, '');
    out += `import feat_${safeName} from './rulebook/feats/${f}.json';\n`;
});
races.forEach(r => {
    const safeName = r.replace(/[^a-zA-Z0-9]/g, '');
    out += `import race_${safeName} from './rulebook/races/${r}.json';\n`;
});
items.forEach(i => {
    const safeName = i.replace(/[^a-zA-Z0-9]/g, '');
    out += `import item_${safeName} from './rulebook/items/${i}.json';\n`;
});
rules.forEach(i => {
    const safeName = i.replace(/[^a-zA-Z0-9]/g, '');
    out += `import rule_${safeName} from './rulebook/rules/${i}.json';\n`;
});
spells.forEach(s => {
    const safeName = s.replace(/[^a-zA-Z0-9]/g, '');
    out += `import spell_${safeName} from './rulebook/spells/${s}.json';\n`;
});

// Spell Pool Routers (e.g. warlock-spells.json, wizard-spells.json)
out += `\nexport const spellsMap: Record<string, any> = {\n`;
spells.forEach(s => {
    if (s.includes('spells')) out += `    "${s}": spell_${s.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n`;

out += `\nexport { classesMap, backgroundsMap, racesMap, itemsMap, rulesMap, generalFeatsMap, epicBoonFeatsMap };\n\n`;

// 3. Generate the Registry Maps
out += `export const classRegistry: Record<string, any> = {\n`;
classes.forEach(c => {
    if (!c.includes('class')) out += `    "${c}": class_${c.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const subclassRegistry: Record<string, any> = {\n`;
classes.forEach(c => {
    if (c.includes('subclass')) out += `    "${c}": class_${c.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const classChoiceRegistry: Record<string, any> = {\n`;
classChoices.forEach(cc => {
    out += `    "${cc}": classChoice_${cc.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const featRegistry: Record<string, any> = {\n`;
feats.forEach(f => {
    out += `    "${f}": feat_${f.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const raceRegistry: Record<string, any> = {\n`;
races.forEach(r => {
    out += `    "${r}": race_${r.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const itemRegistry: Record<string, any> = {\n`;
items.forEach(i => {
    out += `    "${i}": item_${i.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const ruleRegistry: Record<string, any> = {\n`;
rules.forEach(i => {
    out += `    "${i}": rule_${i.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const spellRegistry: Record<string, any> = {\n`;
spells.forEach(s => {
    if (!s.includes('spells')) out += `    "${s}": spell_${s.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n`;

// 4. Generate the Markdown Notes Registry
out += `\nexport const MarkdownNotes: Record<string, string> = {\n`;

markdownNotes.forEach(note => {
    const content = fs.readFileSync(note.filePath, 'utf-8');
    out += `    "${note.name}": ${JSON.stringify(content)},\n`;
});

out += `};\n`;

// --- 5. Generate Past Editions Registry ---
const pastEditionsDir = path.join(rulebookDir, '#past-editions');
out += `\nexport const pastEditionsRegistry: Record<string, any> = {};\n`;

if (fs.existsSync(pastEditionsDir)) {
    // Find all folders inside #past-editions (e.g., "5e")
    const editions = fs.readdirSync(pastEditionsDir).filter(f => fs.statSync(path.join(pastEditionsDir, f)).isDirectory());

    editions.forEach(edition => {
        out += `pastEditionsRegistry["${edition}"] = {\n`;
        out += `    classesMap: {}, backgroundsMap: {}, racesMap: {}, itemsMap: {}, rulesMap: {}, generalFeatsMap: {}, epicBoonFeatsMap: {}, spellsMap: {},\n`;
        out += `    classRegistry: {}, subclassRegistry: {}, classChoiceRegistry: {}, featRegistry: {}, raceRegistry: {}, itemRegistry: {}, ruleRegistry: {}, spellRegistry: {}\n`;
        out += `};\n`;

        // Bundle the maps
        const maps = [
            { file: 'classes', prop: 'classesMap' },
            { file: 'backgrounds', prop: 'backgroundsMap' },
            { file: 'races', prop: 'racesMap' },
            { file: 'items', prop: 'itemsMap' },
            { file: 'rules', prop: 'rulesMap' },
            { file: 'general-feats', prop: 'generalFeatsMap' },
            { file: 'epic-boon-feats', prop: 'epicBoonFeatsMap' }
        ];
        maps.forEach(({ file, prop }) => {
            if (fs.existsSync(path.join(pastEditionsDir, edition, `${file}.json`))) {
                out += `pastEditionsRegistry["${edition}"].${prop} = require('./rulebook/#past-editions/${edition}/${file}.json');\n`;
            }
        });

        // Bundle the registries
        const folders = ['classes', 'feats', 'races', 'items', 'rules', 'spells'];
        folders.forEach(folder => {
            const folderPath = path.join(pastEditionsDir, edition, folder);
            if (fs.existsSync(folderPath)) {
                const files = fs.readdirSync(folderPath).filter(file => file.endsWith('.json')).map(file => file.replace('.json', ''));
                files.forEach(file => {
                    let regName = `${folder.replace(/s$/, '')}Registry`;
                    if (folder === 'classes') {
                        regName = file.includes('subclass') ? 'subclassRegistry' : 'classRegistry';
                    } else if (folder === 'spells') {
                        regName = file.includes('spells') ? 'spellsMap' : 'spellRegistry';
                    }
                    out += `pastEditionsRegistry["${edition}"].${regName}["${file}"] = require('./rulebook/#past-editions/${edition}/${folder}/${file}.json');\n`;
                });
            }
        });

        // Bundle past edition classChoices if present
        const ccPath = path.join(pastEditionsDir, edition, 'classes', 'classChoices');
        if (fs.existsSync(ccPath)) {
            const ccFiles = fs.readdirSync(ccPath).filter(file => file.endsWith('.json')).map(file => file.replace('.json', ''));
            ccFiles.forEach(file => {
                out += `pastEditionsRegistry["${edition}"].classChoiceRegistry["${file}"] = require('./rulebook/#past-editions/${edition}/classes/classChoices/${file}.json');\n`;
            });
        }
    });
}

// Write the compiled text into registry.ts
fs.writeFileSync(outputFile, out);
console.log('✅ Auto-generated registry.ts successfully!');