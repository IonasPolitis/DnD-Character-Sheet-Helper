const fs = require('fs');
const path = require('path');
const { RegularExpressionFlags } = require('typescript/unstable/ast');

const rulebookDir = path.join(__dirname, 'rulebook');
const outputFile = path.join(__dirname, 'registry.ts');

// Helper function to safely read folders and get filenames without '.json'
function scanFolder(folderName) {
    const dirPath = path.join(rulebookDir, folderName);
    if (!fs.existsSync(dirPath)) return [];
    return fs.readdirSync(dirPath)
        .filter(file => file.endsWith('.json'))
        .map(file => file.replace('.json', ''));
}

const classes = scanFolder('classes');
const feats = scanFolder('feats');
const races = scanFolder('races');
const items = scanFolder('items');
const rules = scanFolder('rules');

// --- MARKDOWN NOTE SCANNER ---
// Scans the root directory for any .md files (ignoring the README)
function scanMarkdownNotes() {
    return fs.readdirSync(__dirname)
        .filter(file => file.endsWith('.md') && file.toLowerCase() !== 'readme.md')
        .map(file => file.replace('.md', ''));
}
const markdownNotes = scanMarkdownNotes();

// Start building the file text
let out = `// ==========================================\n`;
out += `// THIS FILE IS AUTO-GENERATED BY A SCRIPT.\n`;
out += `// DO NOT EDIT THIS FILE MANUALLY.\n`;
out += `// ==========================================\n\n`;

// 1. Generate Imports for Upper Routers
out += `import classesMap from './rulebook/classes.json';\n`;
if (fs.existsSync(path.join(rulebookDir, 'backgrounds.json'))) {
    out += `import backgroundsMap from './rulebook/backgrounds.json';\n`;
} else {
    out += `const backgroundsMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'races.json'))) {
    out += `import racesMap from './rulebook/races.json';\n`;
} else {
    out += `const racesMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'items.json'))) {
    out += `import itemsMap from './rulebook/items.json';\n`;
} else {
    out += `const itemsMap = {};\n`;
}
if (fs.existsSync(path.join(rulebookDir, 'rules.json'))) {
    out += `import rulesMap from './rulebook/rules.json';\n`;
} else {
    out += `const rulesMap = {};\n`;
}

// 2. Generate Imports for Sub-folders
classes.forEach(c => {
    // Upgraded Regex: Strips ALL non-alphanumeric characters so JavaScript never breaks
    const safeName = c.replace(/[^a-zA-Z0-9]/g, ''); 
    out += `import class_${safeName} from './rulebook/classes/${c}.json';\n`;
});
feats.forEach(f => {
    const safeName = f.replace(/[^a-zA-Z0-9]/g, '');
    out += `import feat_${safeName} from './rulebook/feats/${f}.json';\n`;
});
races.forEach(r => {
    const safeName = r.replace(/[^a-zA-Z0-9]/g, '');
    out += `import race_${safeName} from './rulebook/races/${r}.json';\n`;
});
items.forEach(i => {
    const safeName = i.replace(/[^a-zA-Z0-9]/g, '');
    out += `import item_${safeName} from './rulebook/items/${i}.json';\n`;
});
rules.forEach(i => {
    const safeName = i.replace(/[^a-zA-Z0-9]/g, '');
    out += `import rule_${safeName} from './rulebook/rules/${i}.json';\n`;
});

out += `\nexport { classesMap, backgroundsMap, racesMap, itemsMap, rulesMap };\n\n`;

// 3. Generate the Registry Maps
out += `export const classRegistry: Record<string, any> = {\n`;
classes.forEach(c => {
    if (!c.includes('class')) out += `    "${c}": class_${c.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const subclassRegistry: Record<string, any> = {\n`;
classes.forEach(c => {
    if (c.includes('subclass')) out += `    "${c}": class_${c.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n\n`;

out += `export const featRegistry: Record<string, any> = {\n`;
feats.forEach(f => {
    out += `    "${f}": feat_${f.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n`;

out += `export const raceRegistry: Record<string, any> = {\n`;
races.forEach(r => {
    out += `    "${r}": race_${r.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n`;

out += `export const itemRegistry: Record<string, any> = {\n`;
items.forEach(i => {
    out += `    "${i}": item_${i.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n`;

out += `export const ruleRegistry: Record<string, any> = {\n`;
rules.forEach(i => {
    out += `    "${i}": rule_${i.replace(/[^a-zA-Z0-9]/g, '')},\n`;
});
out += `};\n`;

// 4. Generate the Markdown Notes Registry
out += `\nexport const MarkdownNotes: Record<string, string> = {\n`;
markdownNotes.forEach(note => {
    const filePath = path.join(__dirname, `${note}.md`);
    const content = fs.readFileSync(filePath, 'utf-8');
    out += `    "${note}": ${JSON.stringify(content)},\n`;
});
out += `};\n`;

// Write the compiled text into registry.ts
fs.writeFileSync(outputFile, out);
console.log('✅ Auto-generated registry.ts successfully!');